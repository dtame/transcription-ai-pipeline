def _yn(value: Any) -> str:
    if value is True or value == "YES":
        return "YES"
    if value is False or value == "NO":
        return "NO"
    if value is None:
        return "UNKNOWN"
    return str(value)


def _dash(value: Any) -> str:
    if value is None:
        return "UNKNOWN"
    return str(value)


