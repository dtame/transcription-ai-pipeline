def header_from_result(result, *, extra: Mapping[str, Any] | None = None) -> dict[str, Any]:
    exe = result.execution or {}
    schema = result.schema_metrics or {}
    cost = (exe.get("cost") or {})
    payload = {
        "result": exe.get("result") or result.mode,
        "real_provider_calls": result.anthropic_post_attempts,
        "authorization_scope": result.authorization_scope,
        "provider": "anthropic",
        "model": "claude-sonnet-5",
        "raw_schema_bytes": schema.get("raw_bytes"),
        "adapted_schema_bytes": schema.get("adapted_bytes"),
        "server_grammar_accepted": exe.get("server_grammar_accepted", "NO"),
        "thinking_disabled_accepted": exe.get("thinking_disabled_accepted", "NO"),
        "http_status": exe.get("http_status"),
        "request_id": exe.get("request_id"),
        "input_tokens": exe.get("input_tokens"),
        "output_tokens": exe.get("output_tokens"),
        "thinking_tokens": exe.get("thinking_tokens"),
        "finish_reason": exe.get("finish_reason"),
        "structured_parse": exe.get("structured_parse", "n/a"),
        "v2_decoder": exe.get("v2_decoder", "n/a"),
        "v2_validator": exe.get("v2_validator", "n/a"),
        "capacity_signal": exe.get("capacity_signal", "n/a"),
        "actual_cost": cost.get("display", "UNKNOWN"),
        "provider_elapsed": exe.get("provider_elapsed_ms"),
        "forensics": exe.get("forensic_path"),
        "canary_artifact_isolated": "YES" if exe.get("canary_artifact_isolated") else (
            "YES" if result.mode == "DRY_RUN" else "NO"
        ),
        "engine_generate_attempts": result.engine_generate_attempts,
        "anthropic_post_attempts": result.anthropic_post_attempts,
        "synthetic_guard_passed": True,
        "synthetic_refs_only": all(
            str(ref) in ("SRC999001", "SRC999002")
            for ref in (exe.get("source_refs") or [])
        )
        if exe
        else True,
        "execution_error": result.error,
        "win001_technically_eligible": (
            "YES — future human authorization only"
            if exe.get("result") == "PASS"
            else "NO"
        ),
    }
    if extra:
        payload.update(dict(extra))
    return payload


def bundle_from_result(
    result,
    *,
    dry_run_1: Mapping[str, Any] | None = None,
    dry_run_2: Mapping[str, Any] | None = None,
    extra_header: Mapping[str, Any] | None = None,
    files_created: list[str] | None = None,
    files_modified: list[str] | None = None,
    dry_run_command: str | None = None,
    real_command: str | None = None,
) -> dict[str, Any]:
    return {
        "header": header_from_result(result, extra=extra_header),
        "dry_run_1": dict(dry_run_1 or result.dry_run or {}),
        "dry_run_2": dict(dry_run_2 or {}),
        "execution": result.execution,
        "payload_audit": result.payload_audit,
        "schema_metrics": result.schema_metrics,
        "freeze": result.freeze,
        "fixture": (result.dry_run or {}).get("fixture") or {},
        "files_created": list(files_created or []),
        "files_modified": list(files_modified or []),
        "dry_run_command": dry_run_command,
        "real_command": real_command,
    }


