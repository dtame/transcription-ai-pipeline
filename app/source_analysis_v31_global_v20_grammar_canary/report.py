        "DISTINCT MEMBERS =",
        _dash(exe.get("distinct_members")),
        "",
        "EXPLICIT DROPS =",
        _dash(exe.get("explicit_drops")),
        "",
        "UNKNOWN MEMBERS =",
        _dash(exe.get("unknown_members")),
        "",
        "DUPLICATE MEMBERS =",
        _dash(exe.get("duplicate_members")),
