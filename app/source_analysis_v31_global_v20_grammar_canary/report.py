        _dash(exe.get("merge_equivalent_count")),
        "",
        "DERIVED DROP =",
        _dash(exe.get("drop_count")),
        "",
        "OTHER =",
        _dash(exe.get("other_count") if exe.get("other_count") is not None else 0),
        "",
        "LINK_RELATED =",
        _dash(exe.get("link_related") if exe.get("link_related") is not None else 0),
        "",
