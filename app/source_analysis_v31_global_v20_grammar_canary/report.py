        str(PRODUCTION_SAFETY_THRESHOLD),
        "",
        "PRODUCTION EXPECTED =",
        str(PRODUCTION_EXPECTED_OUTPUT_TOKENS),
        "",
        "PRODUCTION HARD/PLANNING BOUND =",
        str(PRODUCTION_HARD_PLANNING_TOKENS),
