    elapsed_display = f"{elapsed} ms" if elapsed is not None else "n/a"
    estimator_error = exe.get("estimator_error") or {}
    error_display = "n/a"
    if estimator_error:
        error_display = (
            f"{estimator_error.get('tokens')} tokens / "
            f"{estimator_error.get('percent')}%"
        )
    predicted = exe.get("predicted_canary_output")
    if predicted is None:
        predicted = ((dry.get("output_estimate") or {}).get("expected_provider_tokens"))
    actual_calls = exe.get("actual_calls") if exe else result.anthropic_post_attempts
